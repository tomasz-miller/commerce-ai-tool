// Generates the command list in AGENTS.md from the root package.json scripts, so the two cannot
// drift apart. Every root script needs an entry in DESCRIPTIONS (and no entry may outlive its
// script); otherwise rendering throws.
//
// Usage:
//   node scripts/print-commands.mjs           print the block
//   node scripts/print-commands.mjs --check   exit 1 when AGENTS.md differs from the block
//   node scripts/print-commands.mjs --write   rewrite the block in AGENTS.md
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const BLOCK_START = "<!-- commands:start (generated by scripts/print-commands.mjs, do not edit) -->";
export const BLOCK_END = "<!-- commands:end -->";

