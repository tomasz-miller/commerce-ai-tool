/** Renders the fenced command block (without the markers) for the given root scripts. */
export function renderCommands(scripts, descriptions = DESCRIPTIONS) {
  const names = Object.keys(scripts);
  const undocumented = names.filter((name) => !(name in descriptions));
  const stale = Object.keys(descriptions).filter((name) => !(name in scripts));
  if (undocumented.length > 0 || stale.length > 0) {
    throw new Error(
      [
        undocumented.length > 0 && `scripts without a description in scripts/print-commands.mjs: ${undocumented.join(", ")}`,
        stale.length > 0 && `descriptions for scripts that no longer exist: ${stale.join(", ")}`,
      ]
        .filter(Boolean)
        .join("; "),
    );
  }

  const commands = ["pnpm install"].concat(names.map((name) => `pnpm ${name}`));
  const width = Math.max(...commands.map((command) => command.length));
  const lines = [{ command: "pnpm install", text: "install" }]
    .concat(names.map((name) => ({ command: `pnpm ${name}`, text: descriptions[name] })))
    .map(({ command, text }) => `${command.padEnd(width)}  # ${text}`);
  return ["```bash", ...lines, "```"].join("\n");
}

/** The text between the markers in a markdown document, or `undefined` when they are missing. */
export function extractCommandBlock(markdown) {
  const start = markdown.indexOf(BLOCK_START);
  const end = markdown.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) {
    return undefined;
  }
  return markdown.slice(start + BLOCK_START.length, end).trim();
}

/** Replaces the text between the markers. Throws when the markers are missing. */
export function replaceCommandBlock(markdown, block) {
  const start = markdown.indexOf(BLOCK_START);
  const end = markdown.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`AGENTS.md needs the markers ${BLOCK_START} and ${BLOCK_END}`);
  }
  return `${markdown.slice(0, start + BLOCK_START.length)}\n${block}\n${markdown.slice(end)}`;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const agentsPath = join(root, "AGENTS.md");

export function readRootScripts() {
  return JSON.parse(readFileSync(join(root, "package.json"), "utf8")).scripts;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const block = renderCommands(readRootScripts());
  const mode = process.argv[2];
  if (mode === "--write") {
    writeFileSync(agentsPath, replaceCommandBlock(readFileSync(agentsPath, "utf8"), block));
    console.log("AGENTS.md command block updated.");
  } else if (mode === "--check") {
    if (extractCommandBlock(readFileSync(agentsPath, "utf8")) !== block) {
      console.error("AGENTS.md command block is out of date. Run: node scripts/print-commands.mjs --write");
      process.exit(1);
    }
    console.log("AGENTS.md command block is up to date.");
  } else {
    console.log(block);
  }
}
